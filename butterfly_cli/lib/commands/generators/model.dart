import 'dart:async';
import 'dart:io';
import 'package:args/command_runner.dart';
import 'package:butterfly_cli/extensions/command_helper.dart';
import 'package:butterfly_cli/readable_exception.dart';
import 'package:butterfly_cli/interfaces/interfaces.dart';
import 'package:butterfly_cli/models/model_gen_params.dart';
import 'package:recase/recase.dart';

class ModelGeneratorCommand extends Command with ButterflyLogger {
  final IMasonService _masonService;
  final ICocoonService _cocoonService;

  ModelGeneratorCommand(this._masonService, this._cocoonService) {
    argParser.addFlag('serializable',
        abbr: 's',
        help: 'Generate serializable version (ignored with --cocoon)',
        defaultsTo: true);
    argParser.addFlag('immutable',
        abbr: 'i',
        help: 'Generate immutable model using built_value package',
        defaultsTo: false);
    argParser.addFlag('cocoon',
        abbr: 'c',
        help: 'Generate a Cocoon @Collection model scaffold.\n'
            'The code itself is generated by the project\'s own build_runner\n'
            '(cocoon_generator), never by this CLI.',
        defaultsTo: false,
        negatable: false);
    argParser.addOption('collection',
        help: 'Cocoon collection path for --cocoon models,\n'
            'e.g. accounts/{accountId}/txns ({param} segments are kept as-is).\n'
            'Defaults to the plural snake_case of the name (Txn -> txns).');
    argParser.addOption('path',
        abbr: 'p',
        help: 'Path to generate this model,\n'
            'will start from "project_root/lib/models" directory.\n'
            'If provided, "auth" as param, the directory will be\n'
            '"project_root/lib/models/auth".');
  }

  @override
  String get description => 'Generate a model with JsonSerializable';

  @override
  String get name => 'model';

  @override
  List<String> get aliases => ['m', 'mdl'];

  @override
  Future run() async {
    ensureRoot();

    var className = argResults!.rest.firstOrNull;
    final serializable = argResults!.flag('serializable');
    final immutable = argResults!.flag('immutable');
    final cocoon = argResults!.flag('cocoon');
    final collection = argResults!.option('collection');
    final path = argResults!.option('path');

    if (cocoon && immutable) {
      throw UsageException(
          '--cocoon cannot be combined with --immutable: Cocoon models are\n'
          'plain final-field classes generated from @Collection.',
          usage);
    }

    if (className == null) {
      throw UsageException(
          'Please provide a class name\n'
          'Example: flutter generate model User --serializable --path=auth',
          usage);
    }

    detail("Generate fileName base on $className");
    String fileName = className.snakeCase;
    if (path != null && className.startsWith(path.snakeCase)) {
      detail('path start with class name');
      detail('fileName will be ${className.substring(path.length)}');
      fileName = className.substring(path.length).trim();
    }

    // Handle cases like AuthUsers -> User
    final pathRecase = ReCase(path ?? '');
    final classNameRecase = ReCase(className);
    if (path != null &&
        classNameRecase.pascalCase.startsWith(pathRecase.pascalCase)) {
      fileName = classNameRecase.pascalCase
          .substring(pathRecase.pascalCase.length)
          .trim();
      if (fileName.isEmpty) {
        printUsage();
        throw ReadableException(
          title: 'Invalid class name',
          code: 66,
          message: 'Model name cannot be the same as the path',
          hint: 'Please provide a valid class name or remove the path',
        );
      }
    }

    final directory = Directory(
        '${Directory.current.path}/lib/models/${pathRecase.snakeCase}');
    // Check if the file already exists
    detail('Check if the file already exists');
    final generatedFile = File('${directory.path}/${fileName.snakeCase}.dart');
    detail('File not exist, creating.  ${generatedFile.path}');

    if (generatedFile.existsSync()) {
      info('File already exists at ${generatedFile.absolute.path}');
      final bool overWrite = confirm('Overwrite?', defaultValue: true);

      if (!overWrite) {
        info('Skipping...');
        return;
      }
    }

    final params = ModelGenParams(
      name: className,
      path: directory,
      serializable: serializable,
      fileName: fileName.snakeCase,
    );

    if (cocoon) {
      if (serializable) {
        detail('--serializable is ignored for Cocoon models');
      }
      final hint = _cocoonService.dependencyHint();
      if (hint != null) {
        warn('Missing Cocoon codegen dependencies — add them before running '
            'build_runner:\n$hint');
      }
      final written = await _cocoonService.scaffoldModel(
        className: className,
        path: path,
        collection: collection,
        overwrite: true,
      );
      info('Cocoon model generated at ${written.absolute.path}');
      info('Next steps:\n'
          '  dart run build_runner build -d\n'
          '  butterfly cocoon migrate');
      return;
    }

    if (immutable) {
      await _masonService.generateImmutableModel(params, overwrite: true);
    } else {
      await _masonService.generateModel(params, overwrite: true);
    }

    info('Model generated at ${generatedFile.absolute.path}');
  }
}

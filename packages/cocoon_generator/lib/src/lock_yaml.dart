/// Reading and writing the `cocoon.lock` file's YAML text.
///
/// Reading goes through `package:yaml` ([parseLockYaml]) — the generator is
/// the only package that reads lock files, so only it carries the
/// dependency. Writing is a small emitter of our own ([lockYamlSource]) for
/// exactly the lock's shape, so the file is byte-stable: writing, reading
/// and writing again is byte-identical, and diffs next to the migration
/// files stay as quiet as `pubspec.lock`'s.
library;

import 'package:cocoon/cocoon.dart';
import 'package:yaml/yaml.dart';

/// The committed lock file's name: YAML, written by `migrate`, read by the
/// builder and by `migrate`.
const lockFileName = 'cocoon.lock';

/// The retired JSON name of [lockFileName], read only as the fallback for
/// projects that have not converted yet.
const legacyLockFileName = 'cocoon.lock.json';

/// The `cocoon.lock` file's first line, written by [lockYamlSource].
const lockYamlHeader =
    '# Generated by cocoon_generator migrate. '
    'Do not edit by hand.';

/// Parses `cocoon.lock` YAML text into a [SchemaLock].
///
/// Throws a [FormatException] when the text is not the shape migrate
/// writes (the lock's JSON shape under YAML's flow style included — read
/// the legacy `cocoon.lock.json` with [SchemaLock.parse] instead).
SchemaLock parseLockYaml(String source) {
  final node = loadYaml(source);
  if (node is! YamlMap) {
    throw const FormatException('cocoon.lock must be a YAML mapping');
  }
  return SchemaLock.fromJson(_plainMap(node));
}

Map<String, Object?> _plainMap(YamlMap node) => {
  for (final entry in node.entries)
    entry.key as String: _plainValue(entry.value),
};

/// Copies `package:yaml`'s read-only [YamlMap]/[YamlList] nodes into the
/// plain maps and lists `SchemaLock.fromJson` casts against.
Object? _plainValue(Object? value) => switch (value) {
  final YamlMap map => _plainMap(map),
  final YamlList list => [for (final item in list) _plainValue(item)],
  _ => value,
};

/// The `cocoon.lock` file's deterministic YAML text for [lock]: the header
/// comment, then [SchemaLock.toJson]'s shape — the same stable key order the
/// JSON shape uses — as block style, strings quoted only where YAML needs
/// it, with a trailing newline.
String lockYamlSource(SchemaLock lock) {
  final buffer = StringBuffer()
    ..writeln(lockYamlHeader)
    ..writeln(
      "# Pins every field number, collection path, index and recorded "
      'migration decision of this package\'s Cocoon schema.',
    );
  _writeMap(buffer, lock.toJson(), '');
  return buffer.toString();
}

void _writeMap(StringBuffer buffer, Map<Object?, Object?> map, String indent) {
  for (final MapEntry(key: key, value: value) in map.entries) {
    _writeEntry(buffer, _scalar(key as String), value, indent);
  }
}

void _writeEntry(
  StringBuffer buffer,
  String key,
  Object? value,
  String indent,
) {
  if (value is Map) {
    if (value.isEmpty) {
      buffer.writeln('$indent$key: {}');
      return;
    }
    buffer
      ..writeln('$indent$key:')
      ..write(_mapText(value, '$indent  '));
  } else if (value is List) {
    if (value.isEmpty) {
      buffer.writeln('$indent$key: []');
      return;
    }
    buffer
      ..writeln('$indent$key:')
      ..write(_listText(value, '$indent  '));
  } else {
    buffer.writeln('$indent$key: ${_scalar(value)}');
  }
}

/// Renders [map] as a block mapping whose keys sit at [indent].
String _mapText(Map<Object?, Object?> map, String indent) {
  final buffer = StringBuffer();
  _writeMap(buffer, map, indent);
  return buffer.toString();
}

/// Renders [list] as a block sequence whose items sit at [indent].
///
/// A container item starts on the dash line (`- - x` for a nested list,
/// `- key: x` for a mapping) and continues two spaces deeper, which is where
/// the reader looks for the item's continuation lines.
String _listText(List<Object?> list, String indent) {
  final buffer = StringBuffer();
  for (final item in list) {
    if (item is Map) {
      if (item.isEmpty) {
        buffer.writeln('$indent- {}');
        continue;
      }
      final inner = _mapText(item, '$indent  ');
      _writeDashItem(buffer, inner, indent);
    } else if (item is List) {
      if (item.isEmpty) {
        buffer.writeln('$indent- []');
        continue;
      }
      final inner = _listText(item, '$indent  ');
      _writeDashItem(buffer, inner, indent);
    } else {
      buffer.writeln('$indent- ${_scalar(item)}');
    }
  }
  return buffer.toString();
}

/// Splices an inner block's first line onto the `- ` dash of [indent].
void _writeDashItem(StringBuffer buffer, String inner, String indent) {
  final newline = inner.indexOf('\n');
  final firstLine = newline < 0 ? inner : inner.substring(0, newline);
  final rest = newline < 0 ? '' : inner.substring(newline + 1);
  buffer
    ..write('$indent- ')
    ..write(firstLine.substring(indent.length + 2))
    ..writeln()
    ..write(rest);
}

/// One scalar in block context: ints, bools and plain-safe strings bare,
/// everything else single-quoted (`''` escapes a quote).
String _scalar(Object? value) => switch (value) {
  final String text => _needsQuote(text) ? _quote(text) : text,
  final int number => '$number',
  final bool flag => '$flag',
  _ => throw ArgumentError('A lock cannot contain ${value.runtimeType}'),
};

String _quote(String text) => "'${text.replaceAll("'", "''")}'";

/// Whether [text] must be quoted so a YAML reader resolves it back to the
/// same string: anything a plain scalar would read as null, a bool or a
/// number, strings with leading/trailing whitespace, control characters or
/// a comment/indicator sequence, and single characters an indicator would
/// swallow.
bool _needsQuote(String text) {
  if (text.isEmpty || text.trim() != text) {
    return true;
  }
  for (final code in text.codeUnits) {
    if (code < 0x20 || code == 0x7f) {
      return true;
    }
  }
  final lower = text.toLowerCase();
  if (lower == 'null' ||
      lower == '~' ||
      lower == 'true' ||
      lower == 'false' ||
      lower == '.inf' ||
      lower == '-.inf' ||
      lower == '+.inf' ||
      lower == '.nan') {
    return true;
  }
  if (_numberLike.hasMatch(text)) {
    return true;
  }
  const indicators = ",[]{}#&*!|>'\"%@`";
  final first = text[0];
  if (indicators.contains(first)) {
    return true;
  }
  if ((first == '-' || first == '?' || first == ':') &&
      (text.length == 1 || text[1] == ' ')) {
    return true;
  }
  if (text.contains(': ') || text.endsWith(':') || text.contains(' #')) {
    return true;
  }
  return false;
}

/// Numbers in every spelling `package:yaml` resolves (decimal, hex, octal,
/// exponent, `.`-floats), so a field named like one stays a string on disk.
final RegExp _numberLike = RegExp(
  r'^[-+]?('
  r'[0-9]+'
  r'|0[xX][0-9a-fA-F]+'
  r'|0[oO][0-7]+'
  r'|(\.[0-9]+|[0-9]+(\.[0-9]*)?)([eE][-+]?[0-9]+)?'
  r')$',
);

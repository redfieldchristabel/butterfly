/// SQL naming rules shared by the schema builders and the adapter contract.
///
/// Every Cocoon-owned name is derived deterministically from a Dart name, so
/// generated adapters and hand-written adapters produce identical tables.
library;

/// Pattern a model field or path-param name must match to be indexable.
final RegExp validNamePattern = RegExp(r'^[a-zA-Z][a-zA-Z0-9_]*$');

/// Name of the internal metadata table.
const String metaTableName = '_cocoon_meta';

/// Name of the internal change log table, one row per touched document per
/// committed write.
const String changesTableName = '_cocoon_changes';

/// Name of the internal bulk-load meta table: while a [BulkWriter] runs with
/// deferred indexes it holds one row per dropped secondary index, with the
/// DDL that recreates it. The writer's `close()` and the open-time crash
/// recovery both read it; an empty or absent table means nothing is deferred.
const String bulkTableName = '_cocoon_bulk';

/// Key under which `_cocoon_meta` stores the database's schema version: the
/// lock version the running app last migrated the file to.
const String schemaVersionMetaKey = 'schema_version';

/// Key under which `_cocoon_meta` stores the file's storage format version:
/// how the collection tables are laid out. A file older than
/// [storageFormatVersion] is rebuilt on open; a newer one refuses to open.
const String formatVersionMetaKey = 'format_version';

/// The storage format version this engine writes and reads.
///
/// Version 1 (Cocoon up to and including the step-14 layout) stored a
/// redundant `path TEXT NOT NULL UNIQUE` column and its autoindex in every
/// collection table. Version 2 (this engine) drops both: a document is
/// identified by its scope key (the `p_` param columns plus `id`, enforced
/// by the unique scope index), and the full path is derived from them. An
/// older file is rebuilt table by table inside the open that first touches
/// it; see `FormatMigrator`.
const int storageFormatVersion = 2;

/// Key under which `_cocoon_meta` stores the fingerprint of the schema lock
/// the app passed to [Cocoon.open] (`schemaLock:`), when it did. Written on
/// every open, stamped into backups, and reported by [BackupInfo].
const String schemaLockHashMetaKey = 'schema_lock_hash';

/// Key under which `_cocoon_meta` stores the database's instance id: a
/// random id created with the database, regenerated by `restoreBackup`.
/// Sync consumers compare it against the one they saved before trusting a
/// change-log watermark (see `Cocoon.instanceId`).
const String instanceIdMetaKey = 'instance_id';

/// Keys under which `_cocoon_meta` stores a backup file's metadata, stamped
/// by `backupTo` onto the copy and read by `inspectBackup`. `schema_version`
/// and `schema_lock_hash` arrive with the copied database; the rest are
/// written by the backup itself.
const String backupFormatVersionMetaKey = 'backup_format_version';
const String backupCreatedAtMetaKey = 'backup_created_at';
const String backupLastChangeSeqMetaKey = 'backup_last_change_seq';
const String backupCocoonVersionMetaKey = 'backup_cocoon_version';

/// Converts a Dart identifier to `snake_case`.
///
/// `Txn` becomes `txn`, `AccountNote` becomes `account_note` and acronym runs
/// stay together (`HTTPServer` becomes `http_server`).
String snakeCase(String name) {
  final out = StringBuffer();
  for (var i = 0; i < name.length; i++) {
    final ch = name[i];
    final isUpper = ch.toUpperCase() == ch && ch.toLowerCase() != ch;
    if (isUpper && i > 0) {
      final prev = name[i - 1];
      final prevIsUpper =
          prev.toUpperCase() == prev && prev.toLowerCase() != prev;
      final nextIsLower =
          i + 1 < name.length && name[i + 1].toLowerCase() == name[i + 1];
      if (!prevIsUpper || nextIsLower) {
        out.write('_');
      }
    }
    out.write(ch.toLowerCase());
  }
  return out.toString();
}

/// The SQL table name for a collection model.
///
/// Throws an [ArgumentError] for names Cocoon reserves: anything starting
/// with `sqlite_` (SQLite's own namespace) or `_cocoon` (Cocoon's internal
/// tables), and anything that isn't lowercase letters, digits and underscores.
String tableNameFor(String model) {
  final table = snakeCase(model);
  if (table.startsWith('sqlite_')) {
    throw ArgumentError.value(
      model,
      'model',
      'Table name "$table" may not start with "sqlite_" (reserved by SQLite)',
    );
  }
  if (table.startsWith('_cocoon')) {
    throw ArgumentError.value(
      model,
      'model',
      'Table name "$table" may not start with "_cocoon" (reserved by Cocoon)',
    );
  }
  if (table.isEmpty || !RegExp(r'^[a-z][a-z0-9_]*$').hasMatch(table)) {
    throw ArgumentError.value(
      model,
      'model',
      'Model name must map to a valid SQL table name, got "$table"',
    );
  }
  return table;
}

/// The SQL column name that mirrors a model field (`bookedOn` ->
/// `f_booked_on`).
String fieldColumnName(String fieldName) => 'f_${snakeCase(fieldName)}';

/// The SQL column name that mirrors a path param (`accountId` ->
/// `p_account_id`).
String paramColumnName(String paramName) => 'p_${snakeCase(paramName)}';

/// Whether [name] may be used as a model field or path param in an adapter.
bool isValidColumnName(String name) => validNamePattern.hasMatch(name);
